"""Renders the probe report as the two files the dataset directory versions.

`EXCLUSIONS.md` has to say why a model was rejected, not just that it was: a
corpus filtered by an unrecorded criterion cannot be audited.
"""

from __future__ import annotations

from evaluation.generator.probe import ProbeReport, Verdict

_REASONS: dict[Verdict, str] = {
	Verdict.PARSE_ERROR: "The importer could not read the file at all.",
	Verdict.LOSSY_IMPORT: (
		"The importer read past children the IR does not represent. Injecting into "
		"the remainder would emit a variant missing structure no operator removed."
	),
	Verdict.ROUND_TRIP_FAILED: (
		"The IR does not survive its own export, so a variant would differ from its "
		"seed in ways the ground truth does not record."
	),
	Verdict.TIER1_FINDINGS: (
		"The model is already faulty under tier 1, so an injected defect could not "
		"be told apart from the pre-existing one."
	),
	Verdict.TIER2_UNSOUND: (
		"The model is already unsound, so a SOUND operator has no clean baseline "
		"to violate."
	),
	Verdict.TIER2_UNSUPPORTED: (
		"The tier-2 conversion does not represent a BPMN node type used by the "
		"model, so its soundness verdict would concern a different Petri net."
	),
	Verdict.TIER2_ERROR: (
		"The tier-2 checker failed to return a verdict, which leaves soundness "
		"unknown rather than false."
	),
}


def render_exclusions(report: ProbeReport) -> str:
	"""the markdown body of `EXCLUSIONS.md`"""
	excluded = [record for record in report.records if not record.eligible]
	lines = [
		"# Exclusions",
		"",
		f"Generated by `evaluation/generator/probe.py` v{report.probe_version} from "
		f"`{report.source_dir}`. Regenerate rather than edit.",
		"",
		f"{len(report.seeds)} of {len(report.records)} models passed the seed gate "
		"(METHODOLOGY §2): importable without loss, stable across a round trip, no "
		"tier-1 finding, and sound under tier 2.",
		"",
		"| verdict | models |",
		"|---|---|",
	]
	counts = report.counts()
	for verdict in Verdict:
		if counts.get(verdict.value):
			lines.append(f"| `{verdict.value}` | {counts[verdict.value]} |")
	lines.append("")

	if not excluded:
		lines.append("No model was excluded.")
		return "\n".join(lines) + "\n"

	for verdict in Verdict:
		if verdict is Verdict.ELIGIBLE:
			continue
		group = [record for record in excluded if record.verdict is verdict]
		if not group:
			continue
		lines += [f"## {verdict.value}", "", _REASONS[verdict], ""]
		for record in group:
			lines.append(f"- **{record.seed}** — {record.detail or 'no detail recorded'}")
		lines.append("")

	return "\n".join(lines) + "\n"


def render_seed_list(report: ProbeReport) -> str:
	"""one eligible seed per line, for eyeballing and for shell pipelines"""
	return "".join(f"{record.seed}\n" for record in report.seeds)
